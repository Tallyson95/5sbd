CREATE TABLE transacao (
  transacao_id    INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  conta_numero    INTEGER NOT NULL,
  valor           NUMBER(12,2) NOT NULL,
  data_transacao  DATE DEFAULT SYSDATE,
  CONSTRAINT transacao_pk PRIMARY KEY (transacao_id),
  CONSTRAINT transacao_conta_fk FOREIGN KEY (conta_numero) REFERENCES conta(conta_numero),
  CONSTRAINT transacao_valor_ck CHECK (valor > 0)
);

