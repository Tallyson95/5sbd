  data_cadastro,
  (data_cadastro + INTERVAL '3' MONTH) AS previsao_renovacao
FROM cliente;

-- 9.
CREATE TABLE cartao_credito (
  cartao_numero   VARCHAR2(20) NOT NULL,
  cliente_cod     INTEGER NOT NULL,
  limite_credito  NUMBER(12,2) NOT NULL,
  status          VARCHAR2(10) NOT NULL,
  CONSTRAINT cartao_pk PRIMARY KEY (cartao_numero),
  CONSTRAINT cartao_cliente_fk FOREIGN KEY (cliente_cod) REFERENCES cliente(cliente_cod),
  CONSTRAINT cartao_status_ck CHECK (status IN ('ATIVO','BLOQUEADO','CANCELADO'))
);

