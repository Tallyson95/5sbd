-- 6.
SELECT 
  cliente_cod,
  cliente_nome,
  data_cadastro,
  CASE 
    WHEN data_cadastro IS NULL THEN NULL
    ELSE TRUNC(SYSDATE) - TRUNC(data_cadastro)
  END AS dias_desde_cadastro
FROM cliente;

